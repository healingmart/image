def font(size, bold=False):
    return ImageFont.truetype(BOLD if bold else REG, size)

def add_watermark(path, y_ratio=0.955, opacity=68, size=None):
    im = Image.open(path).convert("RGBA")
    size = size or max(24, round(im.width * 0.017))
    lay = Image.new("RGBA", im.size, (0, 0, 0, 0))
    d = ImageDraw.Draw(lay)
    txt = "healing-mart.com"
    f = font(size, True)
    b = d.textbbox((0, 0), txt, font=f)
    tw, th = b[2]-b[0], b[3]-b[1]
    x = (im.width - tw)//2
    y = int(im.height*y_ratio - th/2)
    pad = max(8, size//3)
    d.rounded_rectangle((x-pad, y-pad//2, x+tw+pad, y+th+pad//2),
                        radius=max(6, size//3),
                        fill=(0, 0, 0, max(18, opacity//3)))
    d.text((x, y), txt, font=f, fill=(235, 255, 247, opacity))
    out = Image.alpha_composite(im, lay).convert("RGB")
    out.save(path, "WEBP", quality=84, method=6)

